package dev.ruchin.anvil.unattend

/** What to automate during Windows Setup. Defaults = what most "my laptop died, reinstall it" users want. */
data class UnattendOptions(
    /** Skip Windows 11's TPM 2.0 / Secure Boot / RAM / CPU / storage checks. */
    val bypassHardwareChecks: Boolean = true,
    /** Create this local account and skip the Microsoft-account screens. null = ask during setup as usual. */
    val localAccount: LocalAccount? = LocalAccount("User"),
    /** Allow finishing setup offline ("I don't have internet") and hide online-account pages. */
    val skipOnlineAccount: Boolean = true,
    /** Answer the privacy/diagnostics questions with "off" and don't show them. */
    val skipPrivacyQuestions: Boolean = true,
    /** Minimum telemetry, no tailored ads/tips, no "consumer experience" auto-installed apps. */
    val reduceTelemetry: Boolean = true,
    /** Stop automatic BitLocker device encryption (avoids surprise recovery-key lockouts later). */
    val disableBitLocker: Boolean = true,
    /** Remove preinstalled promo apps (see [Debloat.PACKAGES]). */
    val removeBloatware: Boolean = false,
    /** Region/keyboard/time zone. null = Setup asks. */
    val region: Region? = null,
)

data class LocalAccount(val name: String, val password: String = "") {
    init { require(isValidName(name)) { "invalid Windows user name" } }

    companion object {
        private val forbidden = "\"/\\[]:;|=,+*?<>@%".toSet()
        fun isValidName(n: String) = n.isNotBlank() && n.length <= 20 && n.none { it in forbidden || it.code < 32 } &&
            !n.endsWith(".") && n.trim() == n &&
            n.lowercase() !in setOf("administrator", "guest", "defaultaccount", "system", "user$", "none")
    }
}

/**
 * @param timeZone Windows time zone id, e.g. "India Standard Time".
 * @param userLocale formats, e.g. "en-IN". @param inputLocale keyboard, e.g. "en-US" or "0409:00000409".
 */
data class Region(val timeZone: String?, val userLocale: String, val inputLocale: String, val systemLocale: String = userLocale)

/** Extra files to place on the USB drive alongside autounattend.xml. */
data class UnattendBundle(val autounattendXml: String, val extraFiles: Map<String, String>)

/**
 * Generates `autounattend.xml` (placed at the USB root, where Windows Setup looks
 * for it automatically) — the same mechanisms Rufus uses:
 *  - windowsPE:   LabConfig registry values → Setup skips the hardware checks
 *  - specialize:  BypassNRO, BitLocker/telemetry/consumer-content policies, debloat script
 *  - oobeSystem:  local account, regional settings, hidden EULA/online-account/privacy pages
 */
object AutounattendBuilder {
    const val DEBLOAT_SCRIPT_PATH = "sources/\$OEM\$/\$\$/Setup/Scripts/anvil-debloat.ps1"

    fun build(options: UnattendOptions, arch: String = "amd64", uiLanguage: String? = null): UnattendBundle {
        require(arch == "amd64" || arch == "arm64" || arch == "x86")
        val extra = LinkedHashMap<String, String>()
        val x = StringBuilder()
        x.appendLine("""<?xml version="1.0" encoding="utf-8"?>""")
        x.appendLine("""<!-- Generated by Anvil. Windows Setup reads this automatically from the USB drive root. -->""")
        x.appendLine("""<unattend xmlns="urn:schemas-microsoft-com:unattend" xmlns:wcm="http://schemas.microsoft.com/WMIConfig/2002/State">""")
        fun component(name: String, body: StringBuilder.() -> Unit) {
            x.appendLine("""    <component name="$name" processorArchitecture="$arch" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS">""")
            x.body()
            x.appendLine("    </component>")
        }
        fun runSync(tag: String, commands: List<String>) {
            if (commands.isEmpty()) return
            x.appendLine("      <$tag>")
            commands.forEachIndexed { i, c ->
                require(c.length <= 259) { "command too long for unattend: $c" }
                x.appendLine("""        <RunSynchronousCommand wcm:action="add"><Order>${i + 1}</Order><Path>${esc(c)}</Path></RunSynchronousCommand>""")
            }
            x.appendLine("      </$tag>")
        }

        // --- windowsPE ---
        if (options.bypassHardwareChecks) {
            x.appendLine("""  <settings pass="windowsPE">""")
            component("Microsoft-Windows-Setup") {
                runSync("RunSynchronous", BYPASS_VALUES.map { "reg add HKLM\\SYSTEM\\Setup\\LabConfig /v $it /t REG_DWORD /d 1 /f" })
            }
            x.appendLine("  </settings>")
        }

        // --- specialize ---
        val spec = ArrayList<String>()
        if (options.skipOnlineAccount) spec += reg("HKLM\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\OOBE", "BypassNRO")
        if (options.disableBitLocker) spec += reg("HKLM\\SYSTEM\\CurrentControlSet\\Control\\BitLocker", "PreventDeviceEncryption")
        if (options.skipPrivacyQuestions) spec += reg("HKLM\\SOFTWARE\\Policies\\Microsoft\\Windows\\OOBE", "DisablePrivacyExperience")
        if (options.reduceTelemetry) {
            spec += reg("HKLM\\SOFTWARE\\Policies\\Microsoft\\Windows\\DataCollection", "AllowTelemetry", 0)
            spec += reg("HKLM\\SOFTWARE\\Policies\\Microsoft\\Windows\\CloudContent", "DisableWindowsConsumerFeatures")
            spec += reg("HKLM\\SOFTWARE\\Policies\\Microsoft\\Windows\\AdvertisingInfo", "DisabledByGroupPolicy")
        }
        if (options.removeBloatware) {
            extra[DEBLOAT_SCRIPT_PATH] = Debloat.script()
            spec += "powershell.exe -NoProfile -ExecutionPolicy Bypass -File %WINDIR%\\Setup\\Scripts\\anvil-debloat.ps1"
        }
        if (spec.isNotEmpty()) {
            x.appendLine("""  <settings pass="specialize">""")
            component("Microsoft-Windows-Deployment") { runSync("RunSynchronous", spec) }
            x.appendLine("  </settings>")
        }

        // --- oobeSystem ---
        val acct = options.localAccount
        val region = options.region
        if (acct != null || region != null || options.skipPrivacyQuestions || options.skipOnlineAccount) {
            x.appendLine("""  <settings pass="oobeSystem">""")
            if (region != null) component("Microsoft-Windows-International-Core") {
                appendLine("      <InputLocale>${esc(region.inputLocale)}</InputLocale>")
                appendLine("      <SystemLocale>${esc(region.systemLocale)}</SystemLocale>")
                uiLanguage?.let { appendLine("      <UILanguage>${esc(it)}</UILanguage>") }
                appendLine("      <UserLocale>${esc(region.userLocale)}</UserLocale>")
            }
            component("Microsoft-Windows-Shell-Setup") {
                appendLine("      <OOBE>")
                appendLine("        <HideEULAPage>true</HideEULAPage>")
                if (options.skipOnlineAccount || acct != null) {
                    appendLine("        <HideOnlineAccountScreens>true</HideOnlineAccountScreens>")
                }
                if (options.skipPrivacyQuestions) appendLine("        <ProtectYourPC>3</ProtectYourPC>")
                appendLine("      </OOBE>")
                if (acct != null) {
                    appendLine("      <UserAccounts>")
                    appendLine("        <LocalAccounts>")
                    appendLine("""          <LocalAccount wcm:action="add">""")
                    appendLine("            <Name>${esc(acct.name)}</Name>")
                    appendLine("            <DisplayName>${esc(acct.name)}</DisplayName>")
                    appendLine("            <Group>Administrators</Group>")
                    appendLine("            <Password><Value>${esc(acct.password)}</Value><PlainText>true</PlainText></Password>")
                    appendLine("          </LocalAccount>")
                    appendLine("        </LocalAccounts>")
                    appendLine("      </UserAccounts>")
                    if (acct.password.isEmpty()) {
                        // Like Rufus: no password baked into the USB; Windows asks for one at first sign-in.
                        appendLine("      <FirstLogonCommands>")
                        appendLine("""        <SynchronousCommand wcm:action="add"><Order>1</Order><CommandLine>${esc("net user \"${acct.name}\" /logonpasswordchg:yes")}</CommandLine></SynchronousCommand>""")
                        appendLine("        <SynchronousCommand wcm:action=\"add\"><Order>2</Order><CommandLine>${esc("net accounts /maxpwage:unlimited")}</CommandLine></SynchronousCommand>")
                        appendLine("      </FirstLogonCommands>")
                    }
                }
                region?.timeZone?.let { appendLine("      <TimeZone>${esc(it)}</TimeZone>") }
            }
            x.appendLine("  </settings>")
        }
        x.appendLine("</unattend>")
        return UnattendBundle(x.toString(), extra)
    }

    /** Windows UI language from a Microsoft ISO label, e.g. "CCCOMA_X64FRE_EN-US_DV9" → "en-US". */
    fun languageFromIsoLabel(label: String?): String? {
        val m = Regex("_([A-Za-z]{2,3})-([A-Za-z]{2,4})_").find(label ?: return null) ?: return null
        return m.groupValues[1].lowercase() + "-" + m.groupValues[2].uppercase()
    }

    val BYPASS_VALUES = listOf("BypassTPMCheck", "BypassSecureBootCheck", "BypassRAMCheck", "BypassCPUCheck", "BypassStorageCheck")

    private fun reg(key: String, value: String, data: Int = 1) = "reg add \"$key\" /v $value /t REG_DWORD /d $data /f"

    fun esc(s: String) = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;").replace("'", "&apos;")
}

/** Conservative list: promo/preview apps only. Store, Photos, Calculator, Notepad, Terminal, Xbox stay. */
object Debloat {
    val PACKAGES = listOf(
        "Clipchamp.Clipchamp", "Microsoft.BingNews", "Microsoft.BingWeather", "Microsoft.BingSearch",
        "Microsoft.GetHelp", "Microsoft.Getstarted", "Microsoft.MicrosoftOfficeHub",
        "Microsoft.MicrosoftSolitaireCollection", "Microsoft.People", "Microsoft.PowerAutomateDesktop",
        "Microsoft.Todos", "Microsoft.WindowsFeedbackHub", "Microsoft.WindowsMaps", "Microsoft.OutlookForWindows",
        "MSTeams", "MicrosoftCorporationII.MicrosoftFamily", "Microsoft.549981C3F5F10", "Microsoft.Copilot",
        "Microsoft.Windows.DevHome", "Microsoft.MicrosoftJournal",
    )

    fun script(): String = buildString {
        appendLine("# Anvil: remove preinstalled promotional apps for all future users (runs once during Windows Setup).")
        appendLine("\$ErrorActionPreference = 'SilentlyContinue'")
        appendLine("\$apps = @(" + PACKAGES.joinToString(", ") { "'$it'" } + ")")
        appendLine("Get-AppxProvisionedPackage -Online | Where-Object { \$apps -contains \$_.DisplayName } | ForEach-Object {")
        appendLine("    Remove-AppxProvisionedPackage -Online -PackageName \$_.PackageName -AllUsers | Out-Null")
        appendLine("}")
    }
}

